package com.example.jdbcdemo;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Savepoint;
import java.sql.Statement;

public class JdbcDemo {
    private static final String JDBC_URL = "jdbc:h2:mem:jdbc_demo;DB_CLOSE_DELAY=-1";
    private static final int BATCH_SIZE = 10_000;

    public static void main(String[] args) throws SQLException {
        try (Connection connection = DriverManager.getConnection(JDBC_URL, "sa", "")) {
            createSchema(connection);
            demonstrateSqlInjection(connection);
            compareBatchUpdates(connection);
            demonstrateTransactions(connection);
        }
    }

    private static void createSchema(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE users (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username VARCHAR(80) NOT NULL,
                        password VARCHAR(80) NOT NULL
                    )
                    """);
            statement.execute("""
                    INSERT INTO users (username, password)
                    VALUES ('alice', 'correct-horse')
                    """);
            statement.execute("""
                    CREATE TABLE accounts (
                        account_name VARCHAR(40) PRIMARY KEY,
                        balance DECIMAL(12, 2) NOT NULL
                    )
                    """);
            statement.execute("""
                    INSERT INTO accounts (account_name, balance) VALUES
                    ('Alice', 1000.00),
                    ('Bob', 500.00),
                    ('Carol', 200.00)
                    """);
            statement.execute("""
                    CREATE TABLE statement_batch (id INTEGER PRIMARY KEY, label VARCHAR(40))
                    """);
            statement.execute("""
                    CREATE TABLE prepared_batch (id INTEGER PRIMARY KEY, label VARCHAR(40))
                    """);
        }
    }

    private static void demonstrateSqlInjection(Connection connection) throws SQLException {
        section("1. Statement vs PreparedStatement: SQL injection");
        String attackInput = "' OR '1'='1' -- ";
        String password = "not-the-password";

        String vulnerableSql = "SELECT username FROM users WHERE username = '"
                + attackInput + "' AND password = '" + password + "'";
        System.out.println("Untrusted username: " + attackInput);
        System.out.println("Statement SQL: " + vulnerableSql);
        System.out.println("Statement authenticated: " + findUserWithStatement(connection, attackInput, password));
        System.out.println("PreparedStatement authenticated: "
                + findUserWithPreparedStatement(connection, attackInput, password));
        System.out.println("The injected input changes the Statement query's logic; the prepared query treats it as data.");
    }

    private static boolean findUserWithStatement(Connection connection, String username, String password)
            throws SQLException {
        String sql = "SELECT username FROM users WHERE username = '"
                + username + "' AND password = '" + password + "'";
        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(sql)) {
            return resultSet.next();
        }
    }

    private static boolean findUserWithPreparedStatement(Connection connection, String username, String password)
            throws SQLException {
        String sql = "SELECT username FROM users WHERE username = ? AND password = ?";
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, username);
            statement.setString(2, password);
            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next();
            }
        }
    }

    private static void compareBatchUpdates(Connection connection) throws SQLException {
        section("2. Batch updates: Statement vs PreparedStatement");
        seedBatchTable(connection, "statement_batch");
        seedBatchTable(connection, "prepared_batch");
        System.out.printf("Updating %,d rows with executeBatch() for each approach.%n", BATCH_SIZE);
        System.out.println("Both use the same connection, transaction boundary, and row count.");

        long statementNanos = timeStatementBatch(connection);
        long preparedNanos = timePreparedStatementBatch(connection);

        System.out.printf("Statement batch:         %.2f ms%n", statementNanos / 1_000_000.0);
        System.out.printf("PreparedStatement batch: %.2f ms%n", preparedNanos / 1_000_000.0);
        System.out.println("Timings are indicative only: JVM warm-up, database, JDBC driver, and hardware affect results.");
        System.out.println("PreparedStatement also avoids rebuilding SQL literals and safely binds each value.");
    }

    private static void seedBatchTable(Connection connection, String tableName) throws SQLException {
        connection.setAutoCommit(false);
        try (PreparedStatement statement = connection.prepareStatement(
                "INSERT INTO " + tableName + " (id, label) VALUES (?, ?)")) {
            for (int id = 1; id <= BATCH_SIZE; id++) {
                statement.setInt(1, id);
                statement.setString(2, "row-" + id);
                statement.addBatch();
            }
            statement.executeBatch();
            connection.commit();
        } catch (SQLException exception) {
            connection.rollback();
            throw exception;
        } finally {
            connection.setAutoCommit(true);
        }
    }

    private static long timeStatementBatch(Connection connection) throws SQLException {
        connection.setAutoCommit(false);
        long start = System.nanoTime();
        try (Statement statement = connection.createStatement()) {
            for (int id = 1; id <= BATCH_SIZE; id++) {
                statement.addBatch("UPDATE statement_batch SET label = 'updated-" + id
                        + "' WHERE id = " + id);
            }
            statement.executeBatch();
            connection.commit();
        } catch (SQLException exception) {
            connection.rollback();
            throw exception;
        } finally {
            connection.setAutoCommit(true);
        }
        return System.nanoTime() - start;
    }

    private static long timePreparedStatementBatch(Connection connection) throws SQLException {
        connection.setAutoCommit(false);
        long start = System.nanoTime();
        try (PreparedStatement statement = connection.prepareStatement(
                "UPDATE prepared_batch SET label = ? WHERE id = ?")) {
            for (int id = 1; id <= BATCH_SIZE; id++) {
                statement.setString(1, "updated-" + id);
                statement.setInt(2, id);
                statement.addBatch();
            }
            statement.executeBatch();
            connection.commit();
        } catch (SQLException exception) {
            connection.rollback();
            throw exception;
        } finally {
            connection.setAutoCommit(true);
        }
        return System.nanoTime() - start;
    }

    private static void demonstrateTransactions(Connection connection) throws SQLException {
        section("3. Transactions: setAutoCommit, commit, rollback, and savepoints");
        connection.setAutoCommit(false);
        try {
            transfer(connection, "Alice", "Bob", BigDecimal.valueOf(200));
            connection.commit();
            System.out.println("Committed transfer: Alice -> Bob, $200.00");
            printBalances(connection);

            transfer(connection, "Alice", "Carol", BigDecimal.valueOf(100));
            System.out.println("Started another transfer: Alice -> Carol, $100.00");
            connection.rollback();
            System.out.println("Rolled back that transfer; balances are unchanged:");
            printBalances(connection);

            transfer(connection, "Alice", "Bob", BigDecimal.valueOf(50));
            Savepoint beforeOptionalAdjustment = connection.setSavepoint("before_optional_adjustment");
            transfer(connection, "Alice", "Carol", BigDecimal.valueOf(25));
            connection.rollback(beforeOptionalAdjustment);
            connection.releaseSavepoint(beforeOptionalAdjustment);
            connection.commit();
            System.out.println("Savepoint: committed Alice -> Bob, $50.00; rolled back only the optional $25.00 transfer to Carol.");
            printBalances(connection);
        } catch (SQLException | RuntimeException exception) {
            try {
                connection.rollback();
            } catch (SQLException rollbackException) {
                exception.addSuppressed(rollbackException);
            }
            throw exception;
        } finally {
            connection.setAutoCommit(true);
        }
    }

    private static void transfer(Connection connection, String from, String to, BigDecimal amount)
            throws SQLException {
        if (amount.signum() <= 0) {
            throw new IllegalArgumentException("Transfer amount must be positive.");
        }
        try (PreparedStatement debit = connection.prepareStatement(
                     "UPDATE accounts SET balance = balance - ? WHERE account_name = ? AND balance >= ?");
             PreparedStatement credit = connection.prepareStatement(
                     "UPDATE accounts SET balance = balance + ? WHERE account_name = ?")) {
            debit.setBigDecimal(1, amount);
            debit.setString(2, from);
            debit.setBigDecimal(3, amount);
            if (debit.executeUpdate() != 1) {
                throw new IllegalStateException("Unknown source account or insufficient funds: " + from);
            }

            credit.setBigDecimal(1, amount);
            credit.setString(2, to);
            if (credit.executeUpdate() != 1) {
                throw new IllegalStateException("Unknown destination account: " + to);
            }
        }
    }

    private static void printBalances(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(
                     "SELECT account_name, balance FROM accounts ORDER BY account_name")) {
            while (resultSet.next()) {
                System.out.printf("  %-6s $%s%n", resultSet.getString("account_name"),
                        resultSet.getBigDecimal("balance").toPlainString());
            }
        }
    }

    private static void section(String title) {
        System.out.println();
        System.out.println("=".repeat(72));
        System.out.println(title);
        System.out.println("=".repeat(72));
    }
}
